        assert_eq!(generate_module(r#""int""#), [] as [GeneratedFile; 0]);
        assert_eq!(
            generate_module(r#"{"type": "array", "items": "long"}"#),
            [] as [GeneratedFile; 0]
        );
        let files = generate_module(r#"["int", "string"]"#);
        let paths: Vec<&str> = files.iter().map(|file| file.path.as_str()).collect();
