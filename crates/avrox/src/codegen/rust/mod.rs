/// Assembles a [`TimeWrapper`] with the standard metadata.
fn build_wrapper(
    name: &'static str,
    kind: LogicalType,
    inner: TokenStream,
    wire: Wire,
    serialize: TokenStream,
    deserialize: TokenStream,
) -> TimeWrapper {
    TimeWrapper {
        name,
        kind,
        inner,
        wire,
        expecting: format!("an Avro `{}` value", kind.avro_name()),
        serialize,
        deserialize,
    }
}

/// Renders a time wrapper newtype with `serde` implementations that encode it
/// as the Avro integer of its logical type.
fn render_time_wrapper(wrapper: &TimeWrapper) -> TokenStream {
    let ident = naming::make_ident(wrapper.name).0;
    let doc = doc_attributes(None, vec![logical_doc_line(wrapper.kind)]);
    let inner = &wrapper.inner;
    let expecting = &wrapper.expecting;
    let serialize = &wrapper.serialize;
    let deserialize = &wrapper.deserialize;
    let wire = wrapper.wire.ty();
    let serialize_fn = format_ident!("serialize_{}", wrapper.wire.suffix());
    let deserialize_fn = format_ident!("deserialize_{}", wrapper.wire.suffix());
    let visit_fn = format_ident!("visit_{}", wrapper.wire.suffix());
    quote! {
        #(#doc)*
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
        pub struct #ident(pub #inner);

        impl serde::Serialize for #ident {
            fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
                serializer.#serialize_fn(
                    (#serialize).ok_or_else(|| serde::ser::Error::custom("value out of range"))?,
                )
            }
        }

        impl<'de> serde::Deserialize<'de> for #ident {
            fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
                struct Visitor;

                impl<'de> serde::de::Visitor<'de> for Visitor {
                    type Value = #ident;

                    fn expecting(&self, formatter: &mut std::fmt::Formatter) -> std::fmt::Result {
                        formatter.write_str(#expecting)
                    }

                    fn #visit_fn<E: serde::de::Error>(self, v: #wire) -> Result<Self::Value, E> {
                        (#deserialize)
                            .map(#ident)
                            .ok_or_else(|| E::custom("value out of range"))
                    }
                }

                deserializer.#deserialize_fn(Visitor)
            }
        }

        impl From<#inner> for #ident {
            fn from(value: #inner) -> Self {
                Self(value)
            }
        }

        impl std::ops::Deref for #ident {
            type Target = #inner;

            fn deref(&self) -> &#inner {
                &self.0
            }
        }
    }
}

/// A `fixed` type as a newtype with `serde` implementations that serialize as
/// Avro bytes, used in [`RustTypes::Std`].
fn render_fixed_newtype(ident: &Ident, doc: &[TokenStream], size: u32) -> TokenStream {
    let array = Literal::usize_unsuffixed(size as usize);
    let expected = format!("a byte array of length {size}");
    quote! {
        #(#doc)*
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]
        pub struct #ident(pub [u8; #array]);

        impl serde::Serialize for #ident {
            fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
                serializer.serialize_bytes(&self.0)
            }
        }

        impl<'de> serde::Deserialize<'de> for #ident {
            fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
                struct FixedVisitor;

                impl<'de> serde::de::Visitor<'de> for FixedVisitor {
                    type Value = #ident;

                    fn expecting(&self, formatter: &mut std::fmt::Formatter) -> std::fmt::Result {
                        formatter.write_str(#expected)
                    }

                    fn visit_bytes<E: serde::de::Error>(self, value: &[u8]) -> Result<Self::Value, E> {
                        <[u8; #array]>::try_from(value)
                            .map(#ident)
                            .map_err(|_| E::invalid_length(value.len(), &#expected))
                    }

                    fn visit_seq<A: serde::de::SeqAccess<'de>>(self, mut seq: A) -> Result<Self::Value, A::Error> {
                        let mut bytes = Vec::with_capacity(#array);
                        while let Some(byte) = seq.next_element::<u8>()? {
                            bytes.push(byte);
                        }
                        <[u8; #array]>::try_from(bytes.as_slice())
                            .map(#ident)
                            .map_err(|_| serde::de::Error::invalid_length(bytes.len(), &#expected))
                    }

                    fn visit_str<E: serde::de::Error>(self, value: &str) -> Result<Self::Value, E> {
                        self.visit_bytes(value.as_bytes())
                    }
                }

                deserializer.deserialize_byte_buf(FixedVisitor)
            }
        }
    }
}

/// Extra doc lines describing the logical type of a `fixed`.
fn fixed_logical_doc_lines(fixed: &Fixed) -> Vec<String> {
    match fixed.logical {
        Some(LogicalType::Decimal { precision, scale }) => {
            vec![format!(
                "Logical type `decimal` (precision {precision}, scale {scale})."
            )]
        }
        Some(LogicalType::Duration) => {
            vec!["Logical type `duration` (months, days and milliseconds).".to_owned()]
        }
        Some(LogicalType::Uuid) => {
            vec!["Logical type `uuid` (RFC 4122 byte layout).".to_owned()]
        }
        _ => Vec::new(),
    }
}

