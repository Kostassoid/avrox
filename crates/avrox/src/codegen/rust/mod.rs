/// The wire type of a time wrapper: the Avro integer the value is encoded as.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Wire {
    I32,
    I64,
}

impl Wire {
    fn ty(self) -> TokenStream {
        match self {
            Self::I32 => quote!(i32),
            Self::I64 => quote!(i64),
        }
    }

    fn suffix(self) -> &'static str {
        match self {
            Self::I32 => "i32",
            Self::I64 => "i64",
        }
    }
}

/// A newtype generated for a time-related logical type under
/// [`RustTime::StdTime`] or [`RustTime::Chrono`].
struct TimeWrapper {
    /// Rust name of the newtype.
    name: &'static str,
    /// The logical type it represents.
    kind: LogicalType,
    /// The wrapped type.
    inner: TokenStream,
    /// The Avro integer the value is encoded as.
    wire: Wire,
    /// What the deserializer expects, for error messages.
    expecting: String,
    /// Expression producing `Option<the wire type>` from `self.0`.
    serialize: TokenStream,
    /// Expression producing `Option<the wrapped type>` from a wire value `v`.
    deserialize: TokenStream,
}

/// Time-related logical types, in the order their wrappers are emitted.
const TIME_KINDS: [LogicalType; 9] = [
    LogicalType::Date,
    LogicalType::TimeMillis,
    LogicalType::TimeMicros,
    LogicalType::TimestampMillis,
    LogicalType::TimestampMicros,
    LogicalType::TimestampNanos,
    LogicalType::LocalTimestampMillis,
    LogicalType::LocalTimestampMicros,
    LogicalType::LocalTimestampNanos,
];

/// The wrapper a time-related logical type maps to under the given settings,
/// or `None` when its underlying integer is used.
fn time_wrapper(time: RustTime, kind: LogicalType) -> Option<TimeWrapper> {
    match time {
        RustTime::Primitives => None,
        RustTime::StdTime => std_time_wrapper(kind),
        RustTime::Chrono => chrono_wrapper(kind).or_else(|| chrono_timestamp_wrapper(kind)),
    }
}

/// The wrappers for the times and instants of [`RustTime::StdTime`].
fn std_time_wrapper(kind: LogicalType) -> Option<TimeWrapper> {
    let (name, inner, wire, serialize, deserialize) = match kind {
        LogicalType::TimestampMillis | LogicalType::LocalTimestampMillis => (
            "TimestampMillis",
            quote!(std::time::SystemTime),
            Wire::I64,
            quote! {
                {
                    let millis = match self.0.duration_since(std::time::UNIX_EPOCH) {
                        Ok(elapsed) => elapsed.as_millis() as i128,
                        Err(before) => -(before.duration().as_millis() as i128),
                    };
                    Some(millis.clamp(i64::MIN as i128, i64::MAX as i128) as i64)
                }
            },
            quote! {
                {
                    let duration = std::time::Duration::from_millis(v.unsigned_abs());
                    if v < 0 {
                        std::time::UNIX_EPOCH.checked_sub(duration)
                    } else {
                        std::time::UNIX_EPOCH.checked_add(duration)
                    }
                }
            },
        ),
        LogicalType::TimestampMicros | LogicalType::LocalTimestampMicros => (
            "TimestampMicros",
            quote!(std::time::SystemTime),
            Wire::I64,
            quote! {
                {
                    let micros = match self.0.duration_since(std::time::UNIX_EPOCH) {
                        Ok(elapsed) => elapsed.as_micros() as i128,
                        Err(before) => -(before.duration().as_micros() as i128),
                    };
                    Some(micros.clamp(i64::MIN as i128, i64::MAX as i128) as i64)
                }
            },
            quote! {
                {
                    let duration = std::time::Duration::from_micros(v.unsigned_abs());
                    if v < 0 {
                        std::time::UNIX_EPOCH.checked_sub(duration)
                    } else {
                        std::time::UNIX_EPOCH.checked_add(duration)
                    }
                }
            },
        ),
        LogicalType::TimestampNanos | LogicalType::LocalTimestampNanos => (
            "TimestampNanos",
            quote!(std::time::SystemTime),
            Wire::I64,
            quote! {
                {
                    let nanos = match self.0.duration_since(std::time::UNIX_EPOCH) {
                        Ok(elapsed) => elapsed.as_nanos() as i128,
                        Err(before) => -(before.duration().as_nanos() as i128),
                    };
                    Some(nanos.clamp(i64::MIN as i128, i64::MAX as i128) as i64)
                }
            },
            quote! {
                {
                    let duration = std::time::Duration::from_nanos(v.unsigned_abs());
                    if v < 0 {
                        std::time::UNIX_EPOCH.checked_sub(duration)
                    } else {
                        std::time::UNIX_EPOCH.checked_add(duration)
                    }
                }
            },
        ),
        LogicalType::TimeMillis => (
            "TimeMillis",
            quote!(std::time::Duration),
            Wire::I32,
            quote! { i32::try_from(self.0.as_millis()).ok() },
            quote! { u64::try_from(v).ok().map(std::time::Duration::from_millis) },
        ),
        LogicalType::TimeMicros => (
            "TimeMicros",
            quote!(std::time::Duration),
            Wire::I64,
            quote! { i64::try_from(self.0.as_micros()).ok() },
            quote! { u64::try_from(v).ok().map(std::time::Duration::from_micros) },
        ),
        _ => return None,
    };
    Some(build_wrapper(
        name,
        kind,
        inner,
        wire,
        serialize,
        deserialize,
    ))
}

/// The wrappers for the wall-clock values of [`RustTime::Chrono`].
fn chrono_wrapper(kind: LogicalType) -> Option<TimeWrapper> {
    let (name, inner, wire, serialize, deserialize) = match kind {
        LogicalType::Date => (
            "Date",
            quote!(chrono::NaiveDate),
            Wire::I32,
            quote! { Some(self.0.to_epoch_days()) },
            quote! { chrono::NaiveDate::from_epoch_days(v) },
        ),
        LogicalType::TimeMillis => (
            "TimeMillis",
            quote!(chrono::NaiveTime),
            Wire::I32,
            quote! {
                i32::try_from(
                    u64::from(chrono::Timelike::hour(&self.0)) * 3_600_000
                        + u64::from(chrono::Timelike::minute(&self.0)) * 60_000
                        + u64::from(chrono::Timelike::second(&self.0)) * 1000
                        + u64::from(chrono::Timelike::nanosecond(&self.0)) / 1_000_000,
                )
                .ok()
            },
            quote! {
                if v < 0 {
                    None
                } else {
                    u32::try_from(v / 1000).ok().and_then(|seconds| {
                        chrono::NaiveTime::from_num_seconds_from_midnight_opt(
                            seconds,
                            (v % 1000) as u32 * 1_000_000,
                        )
                    })
                }
            },
        ),
        LogicalType::TimeMicros => (
            "TimeMicros",
            quote!(chrono::NaiveTime),
            Wire::I64,
            quote! {
                i64::try_from(
                    u64::from(chrono::Timelike::hour(&self.0)) * 3_600_000_000
                        + u64::from(chrono::Timelike::minute(&self.0)) * 60_000_000
                        + u64::from(chrono::Timelike::second(&self.0)) * 1_000_000
                        + u64::from(chrono::Timelike::nanosecond(&self.0)) / 1_000,
                )
                .ok()
            },
            quote! {
                if v < 0 {
                    None
                } else {
                    u32::try_from(v / 1_000_000).ok().and_then(|seconds| {
                        chrono::NaiveTime::from_num_seconds_from_midnight_opt(
                            seconds,
                            (v % 1_000_000) as u32 * 1_000,
                        )
                    })
                }
            },
        ),
        _ => return None,
    };
    Some(build_wrapper(
        name,
        kind,
        inner,
        wire,
        serialize,
        deserialize,
    ))
}

