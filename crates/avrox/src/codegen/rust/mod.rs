//! Rust code generation.
//!
//! Named types are rendered as structs, enums and type aliases; nullable
//! unions as `Option`; other unions as generated enums with one newtype
//! variant per branch, in branch order. The generated code integrates with
//! the [`apache-avro`](https://docs.rs/apache-avro) crate through `serde`
//! derives: `bytes` fields are `serde_bytes::ByteBuf` and `fixed` types are
//! `serde_bytes::ByteArray` aliases, as required by its schema-aware serde
//! implementation.
//!
//! References that recurse through directly nested positions are boxed so
//! that the generated types have finite size; nesting inside arrays, maps and
//! generated union enums never requires boxing on its own.

use std::collections::{BTreeSet, HashMap, HashSet};

use proc_macro2::{Ident, Literal, TokenStream};
use quote::{format_ident, quote};

use crate::error::{Error, Result};
use crate::schema::{
    Document, Enum, Field, Fixed, FullName, LogicalType, NamedType, Record, Schema,
};
use crate::{GeneratedFile, Layout, RustOptions, RustTime, RustTypes};

mod naming;

/// Names used by the generated code itself; schema types mapping to them are
/// rejected as unsupported.
const RESERVED_NAMES: &[&str] = &[
    "std",
    "core",
    "serde",
    "serde_bytes",
    "Box",
    "Option",
    "Vec",
    "String",
    "HashMap",
    "Serialize",
    "Deserialize",
    "ByteBuf",
    "ByteArray",
    "bool",
    "u8",
    "i8",
    "u16",
    "i16",
    "i32",
    "u32",
    "i64",
    "u64",
    "f32",
    "f64",
    "usize",
    "isize",
    "Self",
];

/// Header comment of generated files.
const HEADER: &str = "Generated by avrox from an Avro schema. DO NOT EDIT.";

/// Generates Rust source files for the schema document.
pub(super) fn generate(
    document: &Document,
    layout: Layout,
    options: RustOptions,
) -> Result<Vec<GeneratedFile>> {
    let generator = Generator::new(document, options.types, options.time)?;
    generator.render(layout)
}

/// A node of the nesting graph used to decide where `Box` is required.
///
/// An edge `A -> B` means a value of `B` is nested directly inside a value of
/// `A` without indirection: a named type referenced as a field type or union
/// branch, or a union used as a field type. Arrays and maps add indirection
/// and do not create edges.
#[derive(Clone, PartialEq, Eq, Hash)]
enum Node {
    /// A named type; only records have outgoing edges.
    Type(FullName),
    /// A distinct union, identified by its registration index.
    Union(usize),
}

/// A union registered while walking the schema.
struct UnionInfo {
    /// Rust type name, or `None` when the union is rendered inline as the
    /// branch itself or as an `Option`.
    name: Option<String>,
    /// Branch schemas in declaration order.
    branches: Vec<Schema>,
}

/// How a union is rendered in Rust.
#[derive(Clone, Copy, PartialEq, Eq)]
enum UnionRendering {
    /// A single branch: rendered as the branch itself.
    Transparent,
    /// `null` plus one other branch: rendered as an `Option`.
    Nullable {
        /// Index of the non-null branch.
        other: usize,
    },
    /// A generated enum with one variant per branch.
    Enum,
}

/// Renders a schema document as Rust source code.
struct Generator<'a> {
    document: &'a Document,
    types: RustTypes,
    time: RustTime,
    type_names: HashMap<FullName, String>,
    unions: Vec<UnionInfo>,
    union_ids: HashMap<String, usize>,
    edges: HashMap<Node, Vec<Node>>,
}

/// An import a generated file may need.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Import {
    Serde,
    ByteArray,
    ByteBuf,
    HashMap,
}

/// Per-file rendering state: which imports the file needs and which generated
/// types it references.
struct FileContext {
    /// Rust name of the type defined in this file, if any. References to it
    /// are local and must not be imported.
    own_name: Option<String>,
    /// Names referenced from other files, collected for `use super::` imports.
    /// `None` when references stay local: single-file output and `mod.rs`,
    /// which re-exports every generated type instead.
    references: Option<BTreeSet<String>>,
    imports: BTreeSet<Import>,
}

impl FileContext {
    /// A file that contains everything it references locally.
    fn local() -> Self {
        Self {
            own_name: None,
            references: None,
            imports: BTreeSet::new(),
        }
    }

    /// A file defining a single named type that may reference others.
    fn child(own_name: String) -> Self {
        Self {
            own_name: Some(own_name),
            references: Some(BTreeSet::new()),
            imports: BTreeSet::new(),
        }
    }

    fn needs(&mut self, import: Import) {
        self.imports.insert(import);
    }
}

impl<'a> Generator<'a> {
    fn new(document: &'a Document, types: RustTypes, time: RustTime) -> Result<Self> {
        let mut generator = Self {
            document,
            types,
            time,
            type_names: HashMap::new(),
            unions: Vec::new(),
            union_ids: HashMap::new(),
            edges: HashMap::new(),
        };
        generator.collect_type_names()?;
        generator.walk(&document.root, None);
        for named in &document.types {
            if let NamedType::Record(record) = named {
                for field in &record.fields {
                    generator.walk(&field.schema, Some(Node::Type(record.name.clone())));
                }
            }
        }
        Ok(generator)
    }

    /// Assigns a Rust name to every named type, rejecting collisions with
    /// each other and with names used by the generated code.
    fn collect_type_names(&mut self) -> Result<()> {
        let mut used: HashSet<String> = HashSet::new();
        for named in &self.document.types {
            let rust_name = naming::to_upper_camel_case(&named.name().name);
            if RESERVED_NAMES.contains(&rust_name.as_str())
                || (self.types == RustTypes::Std && rust_name == "Bytes")
                || time_reserved_names(self.time).contains(&rust_name.as_str())
            {
                return Err(Error::Unsupported(format!(
                    "type name `{rust_name}` (from type `{}`) collides with a name used by \
                     the generated code",
                    named.name()
                )));
            }
            if !used.insert(rust_name.clone()) {
                return Err(Error::Unsupported(format!(
                    "multiple types map to Rust type name `{rust_name}` (e.g. `{}`); \
                     generating types with colliding names from different namespaces is not \
                     supported yet",
                    named.name()
                )));
            }
            self.type_names.insert(named.name().clone(), rust_name);
        }
        Ok(())
    }

    /// Registers every union of the schema tree and the nesting graph edges
    /// of directly nested positions.
    fn walk(&mut self, schema: &Schema, container: Option<Node>) {
        match schema {
            Schema::Record(name) | Schema::Enum(name) | Schema::Fixed(name) => {
                if let Some(container) = container {
                    self.add_edge(container, Node::Type(name.clone()));
                }
            }
            Schema::Array(items) | Schema::Map(items) => self.walk(items, None),
            Schema::Union(branches) => {
                let id = self.register_union(branches);
                if let Some(container) = container {
                    self.add_edge(container, Node::Union(id));
                }
                for branch in branches {
                    self.walk(branch, Some(Node::Union(id)));
                }
            }
            Schema::Logical { base, .. } => self.walk(base, container),
            Schema::Null
            | Schema::Boolean
            | Schema::Int
            | Schema::Long
            | Schema::Float
            | Schema::Double
            | Schema::Bytes
            | Schema::String => {}
        }
    }

    fn add_edge(&mut self, from: Node, to: Node) {
        self.edges.entry(from).or_default().push(to);
    }

    /// Registers a union, deduplicating structurally equal ones and naming
    /// the ones rendered as generated enums.
    fn register_union(&mut self, branches: &[Schema]) -> usize {
        let key = union_key(branches);
        if let Some(id) = self.union_ids.get(&key) {
            return *id;
        }
        let name = match union_rendering(branches) {
            UnionRendering::Enum => {
                let base = branch_display_names(branches, &self.type_names, self.time).join("Or");
                Some(self.unique_name(&base))
            }
            _ => None,
        };
        let id = self.unions.len();
        self.unions.push(UnionInfo {
            name,
            branches: branches.to_vec(),
        });
        self.union_ids.insert(key, id);
        id
    }

    /// Derives a unique Rust name for a generated union enum.
    fn unique_name(&self, base: &str) -> String {
        let taken: HashSet<&str> = self
            .type_names
            .values()
            .map(String::as_str)
            .chain(self.unions.iter().filter_map(|union| union.name.as_deref()))
            .collect();
        let mut candidate = base.to_owned();
        let mut suffix = 1;
        while RESERVED_NAMES.contains(&candidate.as_str()) || taken.contains(candidate.as_str()) {
            suffix += 1;
            candidate = format!("{base}{suffix}");
        }
        candidate
    }

    /// The Rust identifier of a named type.
    fn type_ident(&self, name: &FullName) -> (Ident, bool) {
        naming::make_ident(&self.type_names[name])
    }

    /// Renders the output files, or nothing if the schema defines no named
    /// types and no unions.
    fn render(&self, layout: Layout) -> Result<Vec<GeneratedFile>> {
        if self.document.types.is_empty() && !self.has_named_union() {
            return Ok(Vec::new());
        }
        match layout {
            Layout::SingleFile => self.render_single_file(),
            Layout::Module => self.render_module(),
        }
    }

    fn has_named_union(&self) -> bool {
        self.unions.iter().any(|union| union.name.is_some())
    }

    fn render_single_file(&self) -> Result<Vec<GeneratedFile>> {
        let mut context = FileContext::local();
        let mut items = Vec::new();
        if self.types == RustTypes::Std && self.uses_bytes() {
            items.push(Self::render_bytes_type());
        }
        for wrapper in self.used_time_wrappers() {
            items.push(render_time_wrapper(&wrapper));
        }
        for named in &self.document.types {
            items.push(self.render_named(named, &mut context)?);
        }
        for (id, union) in self.unions.iter().enumerate() {
            if union.name.is_some() {
                items.push(self.render_union_enum(id, &mut context)?);
            }
        }
        let imports = imports(&context);
        assemble(output_path(self.document), &imports, &items).map(|file| vec![file])
    }

    /// Renders one file per named type plus a `mod.rs` declaring them,
    /// re-exporting them and holding the generated union enums.
    fn render_module(&self) -> Result<Vec<GeneratedFile>> {
        let mut files = Vec::new();
        let mut mod_decls = Vec::new();
        let mut re_exports = Vec::new();
        if self.types == RustTypes::Std && self.uses_bytes() {
            files.push(assemble(
                "bytes.rs".to_owned(),
                &[],
                &[Self::render_bytes_type()],
            )?);
            mod_decls.push(quote! { pub mod bytes; });
            re_exports.push(quote! { pub use bytes::Bytes; });
        }
        let time_wrappers = self.used_time_wrappers();
        if !time_wrappers.is_empty() {
            let items: Vec<TokenStream> = time_wrappers.iter().map(render_time_wrapper).collect();
            files.push(assemble("time.rs".to_owned(), &[], &items)?);
            mod_decls.push(quote! { pub mod time; });
            let idents: Vec<Ident> = time_wrappers
                .iter()
                .map(|wrapper| naming::make_ident(wrapper.name).0)
                .collect();
            if idents.len() == 1 {
                re_exports.push(quote! { pub use time::#(#idents)*; });
            } else {
                re_exports.push(quote! { pub use time::{#(#idents),*}; });
            }
        }
        for named in &self.document.types {
            let rust_name = self.type_names[named.name()].clone();
            let stem = naming::to_snake_case(&named.name().name);
            let (stem_ident, _) = naming::make_ident(&stem);
            let (type_ident, _) = naming::make_ident(&rust_name);
            let mut context = FileContext::child(rust_name);
            let item = self.render_named(named, &mut context)?;
            let imports = imports(&context);
            files.push(assemble(format!("{stem}.rs"), &imports, &[item])?);
            mod_decls.push(quote! { pub mod #stem_ident; });
            re_exports.push(quote! { pub use #stem_ident::#type_ident; });
        }
        let mut context = FileContext::local();
        let mut unions = Vec::new();
        for (id, union) in self.unions.iter().enumerate() {
            if union.name.is_some() {
                unions.push(self.render_union_enum(id, &mut context)?);
            }
        }
        let imports = imports(&context);
        let tokens = {
            let header = format!(" {HEADER}");
            quote! {
                #![doc = #header]
                #(#mod_decls)*
                #(#imports)*
                #(#re_exports)*
                #(#unions)*
            }
        };
        let file = syn::parse2::<syn::File>(tokens)
            .map_err(|error| Error::Internal(format!("generated invalid Rust: {error}")))?;
        files.insert(
            0,
            GeneratedFile {
                path: "mod.rs".to_owned(),
                contents: prettyplease::unparse(&file),
            },
        );
        Ok(files)
    }

    fn render_named(&self, named: &NamedType, context: &mut FileContext) -> Result<TokenStream> {
        match named {
            NamedType::Record(record) => self.render_record(record, context),
            NamedType::Enum(enum_) => Ok(self.render_enum(enum_, context)),
            NamedType::Fixed(fixed) => Ok(self.render_fixed(fixed, context)),
        }
    }

    fn render_record(&self, record: &Record, context: &mut FileContext) -> Result<TokenStream> {
        context.needs(Import::Serde);
        let (ident, _) = self.type_ident(&record.name);
        let fields = record
            .fields
            .iter()
            .map(|field| self.render_field(field, &record.name, context))
            .collect::<Result<Vec<_>>>()?;
        let doc = doc_attributes(record.doc.as_deref(), Vec::new());
        Ok(quote! {
            #(#doc)*
            #[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
            pub struct #ident {
                #(#fields)*
            }
        })
    }

    fn render_field(
        &self,
        field: &Field,
        record: &FullName,
        context: &mut FileContext,
    ) -> Result<TokenStream> {
        let snake = naming::to_snake_case(&field.name);
        let (ident, escaped) = naming::make_ident(&snake);
        let ty = self.render_type(&field.schema, Some(Node::Type(record.clone())), context)?;
        let doc = doc_attributes(field.doc.as_deref(), logical_doc_lines(&field.schema));
        let name = &field.name;
        let rename = if escaped || snake != *name {
            quote! { #[serde(rename = #name)] }
        } else {
            quote! {}
        };
        Ok(quote! {
            #(#doc)*
            #rename
            pub #ident: #ty,
        })
    }

    fn render_enum(&self, enum_: &Enum, context: &mut FileContext) -> TokenStream {
        context.needs(Import::Serde);
        let (ident, _) = self.type_ident(&enum_.name);
        let mut used: HashSet<String> = HashSet::new();
        let mut variants = Vec::with_capacity(enum_.symbols.len());
        for symbol in &enum_.symbols {
            let camel = naming::to_upper_camel_case(symbol);
            let variant_name = unique_variant_name(&camel, &mut used);
            let (variant, escaped) = naming::make_ident(&variant_name);
            let rename = if escaped || variant_name != *symbol {
                quote! { #[serde(rename = #symbol)] }
            } else {
                quote! {}
            };
            let default = if enum_.default.as_deref() == Some(symbol.as_str()) {
                quote! { #[default] }
            } else {
                quote! {}
            };
            variants.push(quote! {
                #rename
                #default
                #variant,
            });
        }
        let derives = if enum_.default.is_some() {
            quote! { #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default, Serialize, Deserialize)] }
        } else {
            quote! { #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)] }
        };
        let doc = doc_attributes(enum_.doc.as_deref(), Vec::new());
        quote! {
            #(#doc)*
            #derives
            pub enum #ident {
                #(#variants)*
            }
        }
    }

    fn render_fixed(&self, fixed: &Fixed, context: &mut FileContext) -> TokenStream {
        let (ident, _) = self.type_ident(&fixed.name);
        let doc = doc_attributes(fixed.doc.as_deref(), fixed_logical_doc_lines(fixed));
        match self.types {
            RustTypes::ApacheAvro => {
                context.needs(Import::ByteArray);
                let size = Literal::usize_unsuffixed(fixed.size as usize);
                quote! {
                    #(#doc)*
                    pub type #ident = ByteArray<#size>;
                }
            }
            RustTypes::Std => render_fixed_newtype(&ident, &doc, fixed.size),
        }
    }

    /// The `Bytes` newtype generated in [`RustTypes::Std`] for `bytes`
    /// schemas.
    fn render_bytes_type() -> TokenStream {
        quote! {
            /// A byte sequence that serializes as Avro `bytes`.
            #[derive(Debug, Clone, PartialEq, Eq, Hash, Default)]
            pub struct Bytes(pub Vec<u8>);

            impl serde::Serialize for Bytes {
                fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
                    serializer.serialize_bytes(&self.0)
                }
            }

            impl<'de> serde::Deserialize<'de> for Bytes {
                fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
                    struct BytesVisitor;

                    impl<'de> serde::de::Visitor<'de> for BytesVisitor {
                        type Value = Bytes;

                        fn expecting(&self, formatter: &mut std::fmt::Formatter) -> std::fmt::Result {
                            formatter.write_str("a byte array")
                        }

                        fn visit_bytes<E: serde::de::Error>(self, value: &[u8]) -> Result<Self::Value, E> {
                            Ok(Bytes(value.to_vec()))
                        }

                        fn visit_byte_buf<E: serde::de::Error>(self, value: Vec<u8>) -> Result<Self::Value, E> {
                            Ok(Bytes(value))
                        }

                        fn visit_seq<A: serde::de::SeqAccess<'de>>(self, mut seq: A) -> Result<Self::Value, A::Error> {
                            let mut bytes = Vec::new();
                            while let Some(byte) = seq.next_element::<u8>()? {
                                bytes.push(byte);
                            }
                            Ok(Bytes(bytes))
                        }

                        fn visit_str<E: serde::de::Error>(self, value: &str) -> Result<Self::Value, E> {
                            Ok(Bytes(value.as_bytes().to_vec()))
                        }
                    }

                    deserializer.deserialize_byte_buf(BytesVisitor)
                }
            }

            impl From<Vec<u8>> for Bytes {
                fn from(bytes: Vec<u8>) -> Self {
                    Self(bytes)
                }
            }

            impl std::ops::Deref for Bytes {
                type Target = [u8];

                fn deref(&self) -> &[u8] {
                    &self.0
                }
            }
        }
    }

    /// Whether any schema in the document contains a `bytes` type.
    fn uses_bytes(&self) -> bool {
        fn scan(schema: &Schema) -> bool {
            match schema {
                Schema::Bytes => true,
                Schema::Array(items) | Schema::Map(items) | Schema::Logical { base: items, .. } => {
                    scan(items)
                }
                Schema::Union(branches) => branches.iter().any(scan),
                _ => false,
            }
        }
        scan(&self.document.root)
            || self.document.types.iter().any(|named| match named {
                NamedType::Record(record) => record.fields.iter().any(|field| scan(&field.schema)),
                NamedType::Enum(_) | NamedType::Fixed(_) => false,
            })
    }

    /// The time wrapper newtypes the document needs under the current
    /// [`RustTime`] setting, in a deterministic order and without duplicates.
    fn used_time_wrappers(&self) -> Vec<TimeWrapper> {
        fn scan(schema: &Schema, kinds: &mut Vec<LogicalType>) {
            match schema {
                Schema::Logical { kind, .. } => kinds.push(*kind),
                Schema::Array(items) | Schema::Map(items) => scan(items, kinds),
                Schema::Union(branches) => {
                    for branch in branches {
                        scan(branch, kinds);
                    }
                }
                _ => {}
            }
        }
        if self.time == RustTime::Primitives {
            return Vec::new();
        }
        let mut kinds = Vec::new();
        scan(&self.document.root, &mut kinds);
        for named in &self.document.types {
            if let NamedType::Record(record) = named {
                for field in &record.fields {
                    scan(&field.schema, &mut kinds);
                }
            }
        }
        let mut seen = HashSet::new();
        TIME_KINDS
            .iter()
            .filter(|kind| kinds.contains(kind))
            .filter_map(|kind| time_wrapper(self.time, *kind))
            .filter(|wrapper| seen.insert(wrapper.name.to_owned()))
            .collect()
    }

    fn render_union_enum(&self, id: usize, context: &mut FileContext) -> Result<TokenStream> {
        context.needs(Import::Serde);
        let union = &self.unions[id];
        let Some(name) = &union.name else {
            return Err(Error::Internal("inline union has no name".to_owned()));
        };
        let (ident, _) = naming::make_ident(name);
        let mut used: HashSet<String> = HashSet::new();
        let mut variants = Vec::with_capacity(union.branches.len());
        for branch in &union.branches {
            let display = branch_display_name(branch, &self.type_names, self.time);
            let variant_name = unique_variant_name(&display, &mut used);
            let (variant, _) = naming::make_ident(&variant_name);
            let ty = self.render_type(branch, Some(Node::Union(id)), context)?;
            variants.push(quote! { #variant(#ty), });
        }
        let doc = format!(
            " Avro union of {}.",
            branch_display_names(&union.branches, &self.type_names, self.time)
                .into_iter()
                .map(|name| format!("`{name}`"))
                .collect::<Vec<_>>()
                .join(", ")
        );
        let doc_attributes = vec![quote! { #[doc = #doc] }];
        Ok(quote! {
            #(#doc_attributes)*
            #[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
            pub enum #ident {
                #(#variants)*
            }
        })
    }

    /// Renders the Rust type for a schema at a position nested inside
    /// `container`, which is `None` in indirection positions such as array
    /// items and map values.
    fn render_type(
        &self,
        schema: &Schema,
        container: Option<Node>,
        context: &mut FileContext,
    ) -> Result<TokenStream> {
        match schema {
            Schema::Null => Ok(quote!(())),
            Schema::Boolean => Ok(quote!(bool)),
            Schema::Int => Ok(quote!(i32)),
            Schema::Long => Ok(quote!(i64)),
            Schema::Float => Ok(quote!(f32)),
            Schema::Double => Ok(quote!(f64)),
            Schema::Bytes => Ok(self.render_bytes(context)),
            Schema::String => Ok(quote!(String)),
            Schema::Record(name) | Schema::Enum(name) => {
                Ok(self.render_named_ref(name, container.as_ref(), context))
            }
            Schema::Fixed(name) => match self.apache_fixed_type(name) {
                Some(ty) if self.types == RustTypes::ApacheAvro => Ok(ty),
                _ => Ok(self.render_named_ref(name, container.as_ref(), context)),
            },
            Schema::Array(items) => {
                let items = self.render_type(items, None, context)?;
                Ok(quote!(Vec<#items>))
            }
            Schema::Map(values) => {
                context.needs(Import::HashMap);
                let values = self.render_type(values, None, context)?;
                Ok(quote!(HashMap<String, #values>))
            }
            Schema::Union(branches) => self.render_union(branches, container, context),
            Schema::Logical { base, kind } => match time_wrapper(self.time, *kind) {
                Some(wrapper) => {
                    if let Some(references) = &mut context.references {
                        references.insert(wrapper.name.to_owned());
                    }
                    let (ident, _) = naming::make_ident(wrapper.name);
                    Ok(quote!(#ident))
                }
                None => match apache_logical_type(*kind) {
                    Some(ty) if self.types == RustTypes::ApacheAvro => Ok(ty),
                    _ => self.render_type(base, container, context),
                },
            },
        }
    }

    /// The type a `bytes` schema maps to, depending on [`RustTypes`].
    fn render_bytes(&self, context: &mut FileContext) -> TokenStream {
        match self.types {
            RustTypes::ApacheAvro => {
                context.needs(Import::ByteBuf);
                quote!(ByteBuf)
            }
            RustTypes::Std => {
                if let Some(references) = &mut context.references {
                    references.insert("Bytes".to_owned());
                }
                quote!(Bytes)
            }
        }
    }

    /// A reference to a generated named type, boxed when it recurses through
    /// directly nested positions.
    fn render_named_ref(
        &self,
        name: &FullName,
        container: Option<&Node>,
        context: &mut FileContext,
    ) -> TokenStream {
        let rust_name = &self.type_names[name];
        if let Some(references) = &mut context.references
            && context.own_name.as_deref() != Some(rust_name.as_str())
        {
            references.insert(rust_name.clone());
        }
        let (ident, _) = naming::make_ident(rust_name);
        let boxed = container
            .as_ref()
            .is_some_and(|container| self.needs_box(container, name));
        if boxed {
            quote!(Box<#ident>)
        } else {
            quote!(#ident)
        }
    }

    /// The `apache-avro` type a `fixed` with a logical type maps to, if any.
    fn apache_fixed_type(&self, name: &FullName) -> Option<TokenStream> {
        let NamedType::Fixed(fixed) = self.document.get(name)? else {
            return None;
        };
        match fixed.logical {
            Some(LogicalType::Uuid) => Some(quote!(apache_avro::Uuid)),
            Some(LogicalType::Decimal { .. }) => Some(quote!(apache_avro::Decimal)),
            Some(LogicalType::Duration) => Some(quote!(apache_avro::Duration)),
            _ => None,
        }
    }

    fn render_union(
        &self,
        branches: &[Schema],
        container: Option<Node>,
        context: &mut FileContext,
    ) -> Result<TokenStream> {
        let key = union_key(branches);
        let Some(id) = self.union_ids.get(&key).copied() else {
            return Err(Error::Internal(format!("union `{key}` was not registered")));
        };
        match union_rendering(branches) {
            UnionRendering::Transparent => self.render_type(&branches[0], container, context),
            UnionRendering::Nullable { other } => {
                let inner = self.render_type(&branches[other], Some(Node::Union(id)), context)?;
                Ok(quote!(Option<#inner>))
            }
            UnionRendering::Enum => {
                let name = self.unions[id].name.as_deref();
                let Some(name) = name else {
                    return Err(Error::Internal("union enum has no name".to_owned()));
                };
                if let Some(references) = &mut context.references
                    && context.own_name.as_deref() != Some(name)
                {
                    references.insert(name.to_owned());
                }
                let (ident, _) = naming::make_ident(name);
                Ok(quote!(#ident))
            }
        }
    }

    /// Whether a reference to `target` nested directly inside `container`
    /// recurses back into it and must be boxed.
    fn needs_box(&self, container: &Node, target: &FullName) -> bool {
        let mut stack = vec![Node::Type(target.clone())];
        let mut visited = HashSet::new();
        while let Some(node) = stack.pop() {
            if node == *container {
                return true;
            }
            if !visited.insert(node.clone()) {
                continue;
            }
            if let Some(edges) = self.edges.get(&node) {
                stack.extend(edges.iter().cloned());
            }
        }
        false
    }
}

/// Assembles a generated file from its header, imports and items.
fn assemble(path: String, imports: &[TokenStream], items: &[TokenStream]) -> Result<GeneratedFile> {
    let header = format!(" {HEADER}");
    let tokens = quote! {
        #![doc = #header]
        #(#imports)*
        #(#items)*
    };
    let file = syn::parse2::<syn::File>(tokens)
        .map_err(|error| Error::Internal(format!("generated invalid Rust: {error}")))?;
    Ok(GeneratedFile {
        path,
        contents: prettyplease::unparse(&file),
    })
}

/// The `use` statements a generated file needs for its imports.
fn imports(context: &FileContext) -> Vec<TokenStream> {
    let mut uses = Vec::new();
    if context.imports.contains(&Import::Serde) {
        uses.push(quote! { use serde::{Deserialize, Serialize}; });
    }
    match (
        context.imports.contains(&Import::ByteArray),
        context.imports.contains(&Import::ByteBuf),
    ) {
        (true, true) => uses.push(quote! { use serde_bytes::{ByteArray, ByteBuf}; }),
        (true, false) => uses.push(quote! { use serde_bytes::ByteArray; }),
        (false, true) => uses.push(quote! { use serde_bytes::ByteBuf; }),
        (false, false) => {}
    }
    if context.imports.contains(&Import::HashMap) {
        uses.push(quote! { use std::collections::HashMap; });
    }
    if let Some(references) = &context.references
        && !references.is_empty()
    {
        let idents: Vec<Ident> = references
            .iter()
            .map(|name| naming::make_ident(name).0)
            .collect();
        uses.push(quote! { use super::{#(#idents),*}; });
    }
    uses
}

/// The output file path, derived from the root type name.
fn output_path(document: &Document) -> String {
    let stem = match &document.root {
        Schema::Record(name) | Schema::Enum(name) | Schema::Fixed(name) => {
            naming::to_snake_case(&name.name)
        }
        _ => "schema".to_owned(),
    };
    format!("{stem}.rs")
}

/// A structural key identifying a union, used to deduplicate equal unions.
fn union_key(branches: &[Schema]) -> String {
    branches
        .iter()
        .map(Schema::union_branch_key)
        .collect::<Vec<_>>()
        .join("|")
}

/// Determines how a union is rendered in Rust.
fn union_rendering(branches: &[Schema]) -> UnionRendering {
    if branches.len() == 1 {
        return UnionRendering::Transparent;
    }
    if branches.len() == 2 {
        let null_first = matches!(branches[0], Schema::Null);
        let null_second = matches!(branches[1], Schema::Null);
        if null_first != null_second {
            return UnionRendering::Nullable {
                other: usize::from(null_first),
            };
        }
    }
    UnionRendering::Enum
}

/// The display name of a union branch, used for generated enum and variant
/// names.
fn branch_display_name(
    schema: &Schema,
    type_names: &HashMap<FullName, String>,
    time: RustTime,
) -> String {
    match schema {
        Schema::Null => "Null".to_owned(),
        Schema::Boolean => "Boolean".to_owned(),
        Schema::Int => "Int".to_owned(),
        Schema::Long => "Long".to_owned(),
        Schema::Float => "Float".to_owned(),
        Schema::Double => "Double".to_owned(),
        Schema::Bytes => "Bytes".to_owned(),
        Schema::String => "String".to_owned(),
        Schema::Record(name) | Schema::Enum(name) | Schema::Fixed(name) => type_names[name].clone(),
        Schema::Array(_) => "Array".to_owned(),
        Schema::Map(_) => "Map".to_owned(),
        Schema::Union(_) => "Union".to_owned(),
        Schema::Logical { kind, base, .. } => match time_wrapper(time, *kind) {
            Some(wrapper) => wrapper.name.to_owned(),
            None => branch_display_name(base, type_names, time),
        },
    }
}

fn branch_display_names(
    branches: &[Schema],
    type_names: &HashMap<FullName, String>,
    time: RustTime,
) -> Vec<String> {
    branches
        .iter()
        .map(|branch| branch_display_name(branch, type_names, time))
        .collect()
}

/// Derives a unique enum variant name from a candidate.
fn unique_variant_name(candidate: &str, used: &mut HashSet<String>) -> String {
    if used.insert(candidate.to_owned()) {
        return candidate.to_owned();
    }
    let mut suffix = 2;
    while !used.insert(format!("{candidate}{suffix}")) {
        suffix += 1;
    }
    format!("{candidate}{suffix}")
}

/// Builds doc comment attributes from an Avro `doc` and extra lines.
fn doc_attributes(doc: Option<&str>, extra: Vec<String>) -> Vec<TokenStream> {
    let mut lines = Vec::new();
    if let Some(doc) = doc {
        lines.extend(doc.lines().map(str::to_owned));
    }
    lines.extend(extra);
    lines
        .iter()
        .map(|line| {
            let content = if line.is_empty() {
                String::new()
            } else {
                format!(" {line}")
            };
            quote! { #[doc = #content] }
        })
        .collect()
}

