//! Single-file Go code generation with a self-contained Avro binary codec.

use crate::error::{Error, Result};
use crate::schema::{Schema, SchemaNode};
use crate::{AvroVersion, GeneratedFile, Layout, Settings};

mod defaults;
mod model;
mod naming;
mod render;
mod runtime;

pub(super) fn generate(schema: &Schema, settings: &Settings) -> Result<Vec<GeneratedFile>> {
    if settings.layout != Layout::SingleFile {
        return Err(Error::Setting(
            "Go code generation only supports single-file layout; module layout is not supported yet"
                .to_owned(),
        ));
    }
    let model = model::Model::new(schema, &settings.go)?;
    if !model.has_output() {
        return Ok(Vec::new());
    }
    let items = render::Renderer::new(&model).render()?;
    let contents = format!(
        "// Generated by avrox {} from an Avro schema. DO NOT EDIT.\n\
         //\n\
         // Settings used for generation:\n\
         //\n\
         // - language: go\n\
         // - avro version: {}\n\
         // - layout: single\n\
         // - go package: {}\n\n\
         package {}\n\n\
         import (\n\
         \t\"bytes\"\n\
         \t\"encoding/binary\"\n\
         \t\"fmt\"\n\
         \t\"io\"\n\
         \t\"math\"\n\
         \t\"sort\"\n\
         \t\"time\"\n\
         \t\"unicode/utf8\"\n\
         )\n\n\
         {}\n{}",
        env!("CARGO_PKG_VERSION"),
        avro_version(schema.version),
        model.package,
        model.package,
        runtime::RUNTIME.trim_start(),
        items
    );
    let contents = format!("{}\n", contents.trim_end());
    Ok(vec![GeneratedFile {
        path: output_path(schema),
        contents,
    }])
}

fn avro_version(version: AvroVersion) -> &'static str {
    match version {
        AvroVersion::V1_10 => "1.10",
        AvroVersion::V1_11 => "1.11",
        AvroVersion::V1_12 => "1.12",
    }
}

fn output_path(schema: &Schema) -> String {
    let stem = match &schema.root {
        SchemaNode::Record(name) | SchemaNode::Enum(name) | SchemaNode::Fixed(name) => {
            naming::to_snake_case(&name.name)
        }
        _ => "schema".to_owned(),
    };
    let stem = stem.trim_start_matches('_');
    let stem = if stem.is_empty() { "schema" } else { stem };
    if go_build_constrained(stem) {
        format!("{stem}_avro.go")
    } else {
        format!("{stem}.go")
    }
}

fn go_build_constrained(stem: &str) -> bool {
    const PLATFORMS: &[&str] = &[
        "386",
        "aix",
        "amd64",
        "android",
        "arm",
        "arm64",
        "darwin",
        "dragonfly",
        "freebsd",
        "illumos",
        "ios",
        "js",
        "linux",
        "loong64",
        "mips",
        "mips64",
        "mips64le",
        "mipsle",
        "netbsd",
        "openbsd",
        "plan9",
        "ppc64",
        "ppc64le",
        "riscv64",
        "s390x",
        "solaris",
        "wasip1",
        "wasm",
        "windows",
    ];
    stem.ends_with("_test")
        || stem
            .rsplit('_')
            .next()
            .is_some_and(|suffix| PLATFORMS.contains(&suffix))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{Language, Settings};

    #[test]
    fn rejects_module_layout() {
        let schema: Schema = r#"{"type":"record","name":"User","fields":[]}"#.parse().unwrap();
        let settings = Settings::new()
            .language(Language::Go)
            .layout(Layout::Module);
        let error = crate::generate(&schema, &settings).unwrap_err();
        assert!(error.to_string().contains("only supports single-file"));
    }

    #[test]
    fn output_files_are_visible_to_the_go_tool() {
        for (name, path) in [
            ("_User", "user.go"),
            ("UserTest", "user_test_avro.go"),
            ("UserWindows", "user_windows_avro.go"),
            ("UserAMD64", "user_amd64_avro.go"),
        ] {
            let source = format!(r#"{{"type":"record","name":"{name}","fields":[]}}"#);
            let schema: Schema = source.parse().unwrap();
            assert_eq!(output_path(&schema), path);
        }
    }

    #[test]
    fn rejects_generated_declaration_collisions() {
        let schema: Schema = r#"{
            "type":"record",
            "name":"Foo",
            "fields":[{"name":"nested","type":{"type":"record","name":"NewFoo","fields":[]}}]
        }"#
        .parse()
        .unwrap();
        let settings = Settings::new().language(Language::Go);
        assert!(crate::generate(&schema, &settings).is_err());

        let schema: Schema = r#"{
            "type":"record",
            "name":"User",
            "fields":[{"name":"writeAvro","type":"string"}]
        }"#
        .parse()
        .unwrap();
        assert!(crate::generate(&schema, &settings).is_err());

        let schema: Schema = r#"{
            "type":"record",
            "name":"Container",
            "fields":[
                {"name":"e","type":{"type":"enum","name":"IntOr","symbols":["STRING"]}},
                {"name":"u","type":["int","string"]}
            ]
        }"#
        .parse()
        .unwrap();
        assert!(crate::generate(&schema, &settings).is_err());
    }

    #[test]
    fn generates_a_go_package() {
        let schema: Schema = r#"{
            "type":"record",
            "name":"User",
            "namespace":"com.example.profile",
            "fields":[{"name":"id","type":"string"}]
        }"#
        .parse()
        .unwrap();
        let settings = Settings::new().language(Language::Go);
        let files = crate::generate(&schema, &settings).unwrap();
        assert_eq!(files[0].path, "user.go");
        assert!(files[0].contents.contains("package profile"));
        assert!(files[0].contents.contains("ID string `json:\"id\"`"));
        assert!(files[0].contents.contains("func (v *User) WriteAvro"));
    }
}
